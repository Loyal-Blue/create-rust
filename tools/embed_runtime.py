"""Generate the self-contained native runtime from the tested source crates."""
from pathlib import Path


def source(path):
    return path.read_text().replace('//!', '//')


def inline(lib, name, text, public=True):
    declaration = ('pub ' if public else '') + f'mod {name};'
    return lib.replace(declaration, ('pub ' if public else '') + f'mod {name} {{\n' + text + '\n}')


def generate(root):
    crates = root / 'crates'
    native = root / 'native/mixins/create_preview_support'
    transmission = source(crates / 'create-transmission/src/lib.rs')
    transmission = inline(transmission, 'state', source(crates / 'create-transmission/src/state.rs').replace('use crate::{', 'use super::{'))
    transmission = inline(transmission, 'tests', source(crates / 'create-transmission/src/tests.rs'), public=False)
    recipes = source(crates / 'create-recipes/src/lib.rs')
    recipes = inline(recipes, 'containers', source(crates / 'create-recipes/src/containers.rs'), public=False)
    recipes = inline(recipes, 'wood', source(crates / 'create-recipes/src/wood.rs'), public=False)
    recipes = inline(recipes, 'catalog', source(crates / 'create-recipes/src/catalog.rs').replace('use crate::{', 'use super::{'))
    recipes = inline(recipes, 'tests', source(crates / 'create-recipes/src/tests.rs'), public=False)
    machines = source(crates / 'create-machines/src/lib.rs')
    for name in ['worldgen', 'transport', 'fluids', 'trees', 'tanks', 'placing', 'crafting', 'applying', 'assembly']:
        machines = inline(machines, name, source(crates / f'create-machines/src/{name}.rs'))
    # A module alias is inherited by nested tests; rewriting relative paths
    # throughout a nested module would resolve differently under cfg(test).
    for name in ['tanks','crafting','applying','assembly']:
        machines = machines.replace(f'mod {name} {{\n', f'mod {name} {{\nuse super::create_simulation;\n')
    machines = inline(machines, 'surface', 'use super::create_simulation;\n' + source(crates / 'create-machines/src/surface.rs'))
    machines = inline(machines, 'tests', source(crates / 'create-machines/src/tests.rs'), public=False)
    machines = 'use super::recipes as create_simulation;\n' + machines.replace('pub use create_kinetics as kinetics;', 'pub use super::transmission as kinetics;')
    body = '// Generated by tools/embed_runtime.py; edit the source crates and helper bodies.\n'
    for visibility, name, contents in [('', 'kinetic', source(crates / 'create-core/src/lib.rs')), ('pub ', 'transmission', transmission), ('pub ', 'recipes', recipes), ('pub ', 'machines', machines)]:
        body += f'#[allow(dead_code)]\n{visibility}mod {name} {{\n{contents}\n}}\n'
    for file in ['runtime_body.rs', 'machines_body.rs', 'transport_body.rs', 'surface_items.rs', 'surface_body.rs', 'tanks_body.rs', 'placing_body.rs', 'crafting_body.rs', 'assembly_items.rs', 'applying_body.rs']:
        body += source(native / file) + '\n'
    (native / 'runtime.rs').write_text(body.rstrip() + '\n')
